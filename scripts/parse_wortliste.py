def build_goethe_entries() -> list[dict]:
    """Build vocabulary entries from the curated data dictionaries."""
    entries: list[dict] = []
    seen: set[tuple[str, str]] = set()

    # 1. Add nouns from NOUN_DATA
    for word, (gender, plural) in NOUN_DATA.items():
        key = (word.lower(), "noun")
        if key in seen:
            continue
        seen.add(key)

        english = TRANSLATIONS.get(word, "")
        if not english:
            continue

        entry: dict = {
            "german": word,
            "english": english,
            "part_of_speech": "noun",
            "gender": gender,
            "level": "A2",
            "source": "goethe-wortliste",
        }
        if plural is not None:
            entry["plural"] = plural
        else:
            entry["plural"] = None

        group = WORD_TO_GROUP.get(word)
        if group:
            entry["thematic_group"] = group

        entries.append(entry)

    # 2. Add verbs from VERB_DATA
    for word, (pres3p, pp, aux, sep) in VERB_DATA.items():
        key = (word.lower(), "verb")
        if key in seen:
            continue
        seen.add(key)

        english = TRANSLATIONS.get(word, "")
        if not english:
            continue

        entry = {
            "german": word,
            "english": english,
            "part_of_speech": "verb",
            "level": "A2",
            "source": "goethe-wortliste",
            "verb_forms": {
                "present_3p": pres3p,
                "past_participle": pp,
                "auxiliary": aux,
            },
        }
        if sep:
            entry["separable_prefix"] = True

        entries.append(entry)

    # 3. Add adjectives
    for word in sorted(ADJECTIVE_WORDS):
        key = (word.lower(), "adjective")
        if key in seen:
            continue
        seen.add(key)

        english = TRANSLATIONS.get(word, "")
        if not english:
            continue

        entry = {
            "german": word,
            "english": english,
            "part_of_speech": "adjective",
            "level": "A2",
            "source": "goethe-wortliste",
        }

        group = WORD_TO_GROUP.get(word)
        if group:
            entry["thematic_group"] = group

        entries.append(entry)

    return entries


