def merge_vocabulary(
    existing: list[dict], new_entries: list[dict], pos_filter: str
) -> list[dict]:
    """Merge new entries into existing vocabulary, deduplicating by (german.lower(), pos).

    - Existing AI-generated words keep their english translation
    - Goethe entries add enrichment fields (verb_forms, thematic_group, source, etc.)
    - For duplicates, source becomes "both"
    """
    # Index existing by (german_lower, pos)
    index: dict[tuple[str, str], dict] = {}
    for word in existing:
        key = (word["german"].lower(), word["part_of_speech"])
        index[key] = word

    # Merge new entries
    for entry in new_entries:
        if entry["part_of_speech"] != pos_filter:
            continue

        key = (entry["german"].lower(), entry["part_of_speech"])

        if key in index:
            # Merge: existing keeps its english, we add enrichment
            existing_word = index[key]
            existing_word["source"] = "both"

            # Add verb_forms if not present
            if "verb_forms" in entry and entry["verb_forms"]:
                if not existing_word.get("verb_forms"):
                    existing_word["verb_forms"] = entry["verb_forms"]

            # Add thematic_group if not present
            if "thematic_group" in entry and entry["thematic_group"]:
                if not existing_word.get("thematic_group"):
                    existing_word["thematic_group"] = entry["thematic_group"]

            # Add separable_prefix if not present
            if "separable_prefix" in entry and entry["separable_prefix"]:
                if not existing_word.get("separable_prefix"):
                    existing_word["separable_prefix"] = entry["separable_prefix"]

            # For nouns: update plural if missing
            if pos_filter == "noun" and entry.get("plural") is not None:
                if not existing_word.get("plural"):
                    existing_word["plural"] = entry["plural"]
        else:
            # New word, add it
            index[key] = entry

    # Return sorted by german word
    return sorted(index.values(), key=lambda w: w["german"].lower())


def save_vocabulary(filepath: Path, words: list[dict]) -> None:
    """Save vocabulary to JSON file with proper formatting."""
    data = {"words": words}
    with open(filepath, "w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=2)
        fh.write("\n")


def main() -> None:
    """Parse Goethe A2 Wortliste and merge with existing vocabulary."""
    vocab_dir = PROJECT_ROOT / "resources" / "vocabulary"

    # Build Goethe entries from curated data
    goethe_entries = build_goethe_entries()
    nouns = [e for e in goethe_entries if e["part_of_speech"] == "noun"]
    verbs = [e for e in goethe_entries if e["part_of_speech"] == "verb"]
    adjectives = [e for e in goethe_entries if e["part_of_speech"] == "adjective"]

    print(f"Goethe entries parsed: {len(goethe_entries)}")
    print(f"  Nouns: {len(nouns)}")
    print(f"  Verbs: {len(verbs)}")
    print(f"  Adjectives: {len(adjectives)}")

    # Tag existing words with source if not already tagged
    for category in ["nouns", "verbs", "adjectives"]:
        filepath = vocab_dir / f"{category}.json"
        existing = load_existing(filepath)
        for word in existing:
            if not word.get("source"):
                word["source"] = "ai-generated"

    # Load and merge each category
    for category, pos in [("nouns", "noun"), ("verbs", "verb"), ("adjectives", "adjective")]:
        filepath = vocab_dir / f"{category}.json"
        existing = load_existing(filepath)

        # Tag existing words
        for word in existing:
            if not word.get("source"):
                word["source"] = "ai-generated"

        merged = merge_vocabulary(existing, goethe_entries, pos)
        save_vocabulary(filepath, merged)

        # Count stats
        sources = {}
        for w in merged:
            s = w.get("source", "none")
            sources[s] = sources.get(s, 0) + 1

        print(f"\n{category}: {len(existing)} -> {len(merged)} words")
        print(f"  Sources: {sources}")

    # Validate through Pydantic
    print("\nValidating through Pydantic...")
    from german.vocabulary import load_vocabulary

    vocab = load_vocabulary()
    print(f"Total validated: {len(vocab)}")

    nouns_loaded = load_vocabulary(category="nouns")
    verbs_loaded = load_vocabulary(category="verbs")
    adjs_loaded = load_vocabulary(category="adjectives")
    print(f"Nouns: {len(nouns_loaded)}, Verbs: {len(verbs_loaded)}, Adjectives: {len(adjs_loaded)}")

    sources = {}
    for w in vocab:
        s = w.source or "none"
        sources[s] = sources.get(s, 0) + 1
    print(f"Sources: {sources}")


if __name__ == "__main__":
    main()
